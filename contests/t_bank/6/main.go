// Компания празднует праздник. В честь этого события устраивается торжественный ужин для сотрудников, всего приглашено 2n человек. Ресторан предлагает m различных блюд и располагает одним длинным столом, за которым можно разместить ровно n человек с каждой стороны.
// Выбор блюд называется интересным, если никакие два соседних человека не выбрали одинаковое блюдо. Люди считаются соседями, если:
// они сидят рядом в одном ряду ( на соседних местах)
// они сидят друг напротив друга по разные стороны стола.
// Определите количество различных интересных вариантов выбора блюд. Так как ответ может быть слишком большим, выведите его по модулю 10^9 + 7.
// Входные данные:
// В строке заданы два целых числа n и m ( 1<=n<=10^6, 1<=m<=10^9)
// Выход:
// Одно целое число - количество интересных вариантов по модулю 10^9 + 7

package main

import (
	"fmt"
)

const mod = 1000000007

func power(base, exp int64) int64 {
	res := int64(1)
	base %= mod
	for exp > 0 {
		if exp%2 == 1 {
			res = (res * base) % mod
		}
		base = (base * base) % mod
		exp /= 2
	}
	return res
}

func main() {
	var n, m int64
	if _, err := fmt.Scan(&n, &m); err != nil {
		return
	}

	if m < 1 {
		fmt.Println(0)
		return
	}
	if n == 0 {
		fmt.Println(0)
		return
	}

	mMod := m % mod

	start := (mMod * ((mMod - 1 + mod) % mod)) % mod

	term1 := (mMod * mMod) % mod
	term2 := (3 * mMod) % mod
	base := (term1 - term2 + mod) % mod
	base = (base + 3) % mod

	ans := (start * power(base, n-1)) % mod

	fmt.Println(ans)
}