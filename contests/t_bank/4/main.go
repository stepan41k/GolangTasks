// В музее нумизматики проходит выставка старинных монет. Экскурсовод рассказал Маше, что в Римской Империи использовались монеты n различных номиналов: a1, a2, ..., an.
// Известно, что 1 = a1 < a2 < ... < an
// и для каждого 1 <= i <= n - 1 номинал ai+1 кратен ai.
// В сувенирной лавке Маша хочет купить вещь стоимостью x. Она может заплатить любую сумму не меньше x, а продавец выдаст сдачу теми же монетами.
// Нужно определить минимальное общее количество монет, которое будет использовано: и тех, которыми Маша платит, и тех, которые она получит в качестве сдачи.
// Более формально, среди всех целых y >= x требуется найти минимум величины (минимальное число монет, чтобы набрать ровно y) + (минимальное число монет, чтобы набрать ровно y - x)
// Входные данные:
// В первой строке даны числа n (1 <= n <= 60) и x (1 <= x <= 10^18) - количество монет и необходимая сумма
// В следующей строке даны n чисел 1 = a1, a2, ..., an (1 <= ai <= 10^18) - номиналы монет. Для всех 1 <= i <= n - 1 число  ai + 1 кратно ai.
// Выход: Одно целое число - минимальное общее количество монет.

package main

import (
	"fmt"
)

type state struct {
	idx int
	rem int64
}

var (
	n    int
	x    int64
	a    []int64
	memo map[state]int64
)

func solve(idx int, rem int64) int64 {
	if rem == 0 {
		return 0
	}

	if idx == n-1 {
		return rem
	}

	s := state{idx, rem}
	if val, ok := memo[s]; ok {
		return val
	}

	c := a[idx+1] / a[idx]

	res := (rem % c) + solve(idx+1, rem/c)

	if rem%c != 0 {
		res2 := (c - (rem % c)) + solve(idx+1, rem/c+1)
		if res2 < res {
			res = res2
		}
	}

	memo[s] = res
	return res
}

func main() {
	if _, err := fmt.Scan(&n, &x); err != nil {
		return
	}

	a = make([]int64, n)
	for i := 0; i < n; i++ {
		if _, err := fmt.Scan(&a[i]); err != nil {
			break
		}
	}

	memo = make(map[state]int64)
	
	result := solve(0, x)
	
	fmt.Println(result)
}